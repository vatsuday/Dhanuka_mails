'use client';

// Two-step verification (S2.1): set up with a QR code, confirm with a code, keep the recovery codes,
// and, for owners, require it for every member of the organisation.
import { useCallback, useEffect, useState, type SubmitEvent } from 'react';
import { api, messageFor } from '../../lib/api';

interface Status {
  enabled: boolean;
  recoveryCodesRemaining: number;
}
interface Enrolment {
  secret: string;
  qrCode: string;
}

export function SecurityCard({ onChange }: { onChange: () => Promise<void> }) {
  const [status, setStatus] = useState<Status>();
  const [enrolment, setEnrolment] = useState<Enrolment>();
  const [recoveryCodes, setRecoveryCodes] = useState<string[]>();
  const [error, setError] = useState('');

  const load = useCallback(async () => {
    setStatus((await api<Status>('/auth/mfa')).data);
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  async function start() {
    setError('');
    const result = await api<Enrolment>('/auth/mfa/enroll', {});
    if (result.ok) setEnrolment(result.data);
    else setError(messageFor(result.data.error));
  }

  async function confirm(event: SubmitEvent<HTMLFormElement>) {
    event.preventDefault();
    setError('');
    const result = await api<{ recoveryCodes: string[] }>('/auth/mfa/confirm', { code: new FormData(event.currentTarget).get('code') });
    if (!result.ok) {
      setError(messageFor(result.data.error));
      return;
    }
    setEnrolment(undefined);
    setRecoveryCodes(result.data.recoveryCodes);
    await load();
    await onChange();
  }

  async function disable(event: SubmitEvent<HTMLFormElement>) {
    event.preventDefault();
    setError('');
    const result = await api('/auth/mfa/disable', { code: new FormData(event.currentTarget).get('code') });
    if (!result.ok) {
      setError(messageFor(result.data.error));
      return;
    }
    setRecoveryCodes(undefined);
    await load();
    await onChange();
  }

  if (status === undefined) return null;

  return (
    <div className="card">
      <h2>Two-step verification</h2>
      {recoveryCodes !== undefined && (
        <>
          <p className="success">Two-step verification is on.</p>
          <p>Save these recovery codes somewhere safe. Each works once, and they will not be shown again.</p>
          <pre className="codes">{recoveryCodes.join('\n')}</pre>
        </>
      )}
      {!status.enabled && enrolment === undefined && (
        <>
          <p className="muted">Protect your account with a code from an authenticator app when you log in.</p>
          <button type="button" onClick={() => void start()}>Set up two-step verification</button>
        </>
      )}
      {!status.enabled && enrolment !== undefined && (
        <form onSubmit={(e) => void confirm(e)}>
          <p>Scan this QR code with your authenticator app, then enter the 6-digit code it shows.</p>
          {/* A data: URI generated by the API. */}
          <img src={enrolment.qrCode} alt="QR code for your authenticator app" width={200} height={200} />
          <p className="muted">
            Can&apos;t scan? Enter this key: <code>{enrolment.secret}</code>
          </p>
          <label htmlFor="mfa-code">Code</label>
          <input id="mfa-code" name="code" type="text" inputMode="numeric" autoComplete="one-time-code" maxLength={6} required />
          <button type="submit">Turn on</button>
        </form>
      )}
      {status.enabled && recoveryCodes === undefined && (
        <form onSubmit={(e) => void disable(e)}>
          <p>
            Two-step verification is on. <span className="muted">{status.recoveryCodesRemaining} recovery codes left.</span>
          </p>
          <label htmlFor="mfa-off">Code to turn it off</label>
          <input id="mfa-off" name="code" type="text" autoComplete="one-time-code" maxLength={32} required />
          <button type="submit" className="secondary">Turn off</button>
        </form>
      )}
      {error !== '' && <p className="error" role="alert">{error}</p>}
    </div>
  );
}

/** Owner-only switch: every member must use two-step verification (S2.1 AC 5). */
export function RequireMfaCard({ requireMfa, onChange }: { requireMfa: boolean; onChange: () => Promise<void> }) {
  const [error, setError] = useState('');

  async function toggle() {
    setError('');
    const result = await api('/orgs/current/security', { requireMfa: !requireMfa });
    if (!result.ok) {
      setError(messageFor(result.data.error));
      return;
    }
    await onChange();
  }

  return (
    <div className="card">
      <h2>Organisation security</h2>
      <p>
        {requireMfa
          ? 'Every member must use two-step verification to open this organisation.'
          : 'Members can open this organisation without two-step verification.'}
      </p>
      <button type="button" className="secondary" onClick={() => void toggle()}>
        {requireMfa ? 'Stop requiring two-step verification' : 'Require two-step verification'}
      </button>
      {error !== '' && <p className="error" role="alert">{error}</p>}
    </div>
  );
}
